const choiceInstruction =
    '해당 항목을 함께 선택하되, 해당 없음·잘 모르겠어요는 다른 항목과 함께 선택하지 마세요.';

export function isOsanSubmissionGuide(question: Question) {
    return (
        question.id === 'mymy' &&
        question.evidence?.url?.split('#')[0] === mymyGuide
    );
}

export function osanConditionDetail(
    question: Question,
): StructuredConditionDetail | undefined {
    if (!matchesSpecializedCondition(question, 'osan')) return;
    const text = (question.reason ?? '').trim();
    if (question.id === 'score' && text.includes('\n배점 기준')) {
        const selection = text.split('\n', 1)[0].trim();
        const tables = qualificationTables({
            eligibility: '',
            selection,
            detail: text,
            evidence: question.evidence,
            reviewRequired: false,
        });
        if (!tables) return;
        const facts = tables.facts.filter(([label]) => label !== '최종 선정');
        const factPages: Record<string, number[]> = {
            '신청 자격': [3],
            '소득·자산': [5],
            '유형 선택': [10],
            '서류 대상 선정': [2, 11],
        };
        const items: DetailItem[] = [
            selection.replace(/입니다\.$/u, '예요.'),
            pages(9, 10),
        ];
        for (const [label, value] of facts) {
            items.push('• ' + label + ' · ' + value);
            if (factPages[label]) items.push(pages(...factPages[label]));
        }
        return {
            ...sectioned(items),
            preview: '서류 대상 선정과 최종 입주 순위는 따로 정해요.',
            tables,
            tableEvidence: {
                '기본 배점': pages(9, 10),
                '일반공급 가점': pages(9),
                '주거약자형 가점': pages(10),
            },
        };
    }
    const hasInstruction = text.endsWith(' ' + choiceInstruction);
    const reason = hasInstruction
        ? text.slice(0, -(choiceInstruction.length + 1))
        : text;
    const entry = reviewed.get(reason);
    if (!entry) return;
    const lines = entry.items;
    const textLines =
        hasInstruction && question.id !== 'household'
            ? [
                  ...lines,
                  '해당하는 항목은 함께 선택할 수 있어요. ‘해당 없음’과 ‘잘 모르겠어요’는 각각 단독으로 선택해요.',
              ]
            : lines;
    return { ...sectioned(textLines), preview: entry.preview };
}
