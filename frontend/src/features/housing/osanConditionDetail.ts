function pages(...numbers: number[]): Evidence[] {
    return numbers.map((page) => ({
        label: '공고문 ' + page + '쪽 보기',
        url: noticePdf + '#page=' + page + '&sha256=' + pageHashes['69203687'],
        checkedAt,
    }));
}

function guide(anchor: string): Evidence[] {
    const encoded = btoa(
        String.fromCharCode(...new TextEncoder().encode(anchor)),
    )
        .replaceAll('+', '-')
        .replaceAll('/', '_')
        .replace(/=+$/, '');
    return [
        {
            label: 'MyMy 이용안내 해당 문단 보기',
            url: mymyGuide + '#doc=' + guideHash + '.0.' + encoded,
            checkedAt,
        },
    ];
}

