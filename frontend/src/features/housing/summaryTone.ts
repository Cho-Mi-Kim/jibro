const sentenceEnd = '(?=[.!?。！？;]|[)\\]}]|\\s|$)';
const endingPattern = new RegExp(
    `(?:${Array.from(endings.keys())
        .sort((a, b) => b.length - a.length)
        .join('|')})${sentenceEnd}`,
    'gu',
);
const pastPattern = new RegExp(`([했됐았었였])습니다${sentenceEnd}`, 'gu');
const nounPattern = new RegExp(
    `([가-힣%OX0-9㎡㎥²³])입니다${sentenceEnd}`,
    'gu',
);

// Quoted source text, code, URLs and filenames are evidence, not our explanation.
const protectedText =
    /(```[\s\S]*?```|`[^`\n]*`|“[^”]*”|‘[^’]*’|「[^」]*」|『[^』]*』|"[^"]*"|'[^']*'|https?:\/\/[^\s<>"'“”‘’]+|[\p{L}\p{N}_./\\:%?=&#+~-]+\.(?:pdf|hwpx?|xlsx?|docx?|zip|csv|txt|html?|json|md|png|jpe?g)(?=\s|[)\]}.,;!?]|$))/giu;

export function mapExplanationText(
    text: string,
    transform: (part: string) => string,
): string {
    return text
        .split(protectedText)
        .map((part, index) => (index % 2 ? part : transform(part)))
        .join('');
}

function sentenceTone(text: string): string {
    return text
        .replace(endingPattern, (ending) => endings.get(ending)!)
        .replace(pastPattern, '$1어요')
        .replace(
            nounPattern,
            (_, last: string) =>
                last +
                (/^[가-힣]$/u.test(last)
                    ? (last.charCodeAt(0) - 0xac00) % 28 === 0
                        ? '예요'
                        : '이에요'
                    : /^[013678]$/.test(last)
                      ? '이에요'
                      : '예요'),
        );
}

export function noticeSummaryText(
    text: string,
    context?: { questions?: Question[] },
): string {
    const reviewedSource = context?.questions?.some((question) =>
        /^https:\/\/apply\.lh\.or\.kr\/lhapply\/lhFile\.do\?fileid=(?:69203687|69355347|68998510)(?:#|$)/u.test(
            question.evidence?.url ?? '',
        ),
    );
    const exact = reviewedSource && sentences.get(text);
    if (exact) return exact;
    return mapExplanationText(text, (part) =>
        part
            .split(' · ')
            .map(
                (piece) =>
                    (reviewedSource && sentences.get(piece)) ||
                    sentenceTone(piece),
            )
            .join(' · '),
    );
}
