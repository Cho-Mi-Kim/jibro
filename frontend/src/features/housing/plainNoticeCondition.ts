export function noticeConditionHeading(title: string) {
    return (
        headings.get(title) ??
        (title
            .replace(/[을를] 확인(?:했나요\?|해 주세요\.)$/, '')
            .replace(/ 제출 대상인가요\?$/, ' 제출 대상') ||
            title)
    );
}

