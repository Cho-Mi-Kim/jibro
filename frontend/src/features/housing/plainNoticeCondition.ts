export function noticeConditionSentence(sentence: string) {
    return (
        sentences.get(sentence) ??
        plainConditionText(sentence)
            .replace(
                /^(.+?) 기준 무주택세대구성원이어야 합니다\.$/u,
                '$1 기준, 심사 대상 세대원 모두 집이 없어야 해요.',
            )
            .replace(
                /^비영업용 승용자동차별 가액 중 최고 가액이 ([\d,]+)\s*만원 이하인지 확인합니다\.$/u,
                '영업용이 아닌 승용차 중 가장 비싼 차의 평가액이 $1만 원 이하여야 해요.',
            )
            .replace(
                /공고일 현재 만\s*(\d+)세 이상이 원칙입니다\./gu,
                '공고일 기준 만 $1세 이상이 원칙이에요.',
            )
            .replace(
                /해당 세대의 자동차가액|해당 세대의 자동차 가액/gu,
                '심사 대상 세대의 자동차 평가액',
            )
            .replace(/주민등록등본에 등재된/gu, '주민등록등본에 올라 있는')
            .replace(/분리 배우자/gu, '등본이 따로인 배우자')
    );
}
