function reviewedEntry(question: Question): ReviewedCondition | undefined {
    const entry = reviewed[question.id];
    if (
        !entry ||
        !matchesSpecializedCondition(question, 'samrye') ||
        question.reason !== entry.reason
    )
        return;
    return entry;
}

export function samryeConditionDetail(
    question: Question,
): StructuredConditionDetail | undefined {
    const entry = reviewedEntry(question);
    return entry && { ...sectioned(entry.items), preview: entry.preview };
}

export function samryeReviewedQuestion(
    notice: Notice,
    id: string,
): Question | undefined {
    if (
        notice.id !== 'ef03d490-e2d2-4247-9df9-65d53d10f043' ||
        notice.publishedDate !== '2026-10-19' ||
        notice.guideVersion !== 7 ||
        notice.guideState !== 'AVAILABLE'
    )
        return;
    const question = notice.questions.find((candidate) => candidate.id === id);
    if (
        !question ||
        question.reviewRequired ||
        questionReviewIssues(notice.reviewIssues, question.id).length ||
        !reviewedEntry(question)
    )
        return;
    return question;
}
