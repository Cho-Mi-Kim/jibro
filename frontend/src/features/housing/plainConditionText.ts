function householdIncomeLines(sentence: string) {
    const values = sentence.match(
        /^(\d+)~(\d+)인가구의(\d+%) 금액은([\d, /]+)원, (\d+%)는([\d, /]+)원입니다\.$/,
    );
    if (!values) return;
    const [, first, last, baseRate, baseAmounts, higherRate, higherAmounts] =
        values;
    const base = baseAmounts.split(' / ');
    const higher = higherAmounts.split(' / ');
    if (
        base.length !== Number(last) - Number(first) + 1 ||
        base.length !== higher.length
    )
        return;
    return base
        .map(
            (amount, i) =>
                `${Number(first) + i}인 가구 · ${baseRate} 기준 ${amount}원 / ${higherRate} 기준 ${higher[i]}원`,
        )
        .join('\n');
}

